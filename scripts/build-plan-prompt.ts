/**
 * npm run plan-prompt (also the first step of npm run build)
 * Writes src/plan/prompt.ts, the Describe-track model's reference and tool: the track plan language
 * (docs/track-plan-language.md), every example plan (docs/plans/examples/*.json) and the submit_plan tool built from
 * src/plan/plan.schema.json. The browser sends them to Anthropic itself (src/plan/anthropic.ts), so they ship in the app.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const read = (path: string) => readFileSync(join(ROOT, path), 'utf8');

/** System prompt blocks after the role brief, each starting with a `# ` heading line. */
const reference = [
  `# Track plan language reference (docs/track-plan-language.md)\n\n${read('docs/track-plan-language.md')}`,
  ...readdirSync(join(ROOT, 'docs/plans/examples')).filter(name => name.endsWith('.json')).sort()
    .map(name => `# Example plan: ${name}\n\n\`\`\`json\n${read(`docs/plans/examples/${name}`).trim()}\n\`\`\`\n`)
];

// Tool input schemas take `$defs` at their root, so the plan schema's move up next to `notes`.
const plan = JSON.parse(read('src/plan/plan.schema.json')) as Record<string, unknown>;
const $defs = plan.$defs;
for (const key of ['$defs', '$schema', '$id']) delete plan[key];
const tool = {
  name: 'submit_plan',
  description: 'Submit the complete track plan v1 for the user\'s layout, with short notes for the user.',
  input_schema: {
    type: 'object', additionalProperties: false, required: ['notes', 'plan'],
    properties: {
      notes: { type: 'string', description: '1-4 plain-language sentences to the user: what you built and any compromise ' +
        '(for example a request that could not fit the room or inventory).' },
      plan
    },
    $defs
  }
};

writeFileSync(join(ROOT, 'src/plan/prompt.ts'), `// Generated by scripts/build-plan-prompt.ts (npm run plan-prompt) from docs/track-plan-language.md,
// docs/plans/examples/*.json and src/plan/plan.schema.json. Do not edit by hand.

/** System prompt blocks after the role brief: the language reference, then every example plan. */
export const PLAN_REFERENCE: readonly string[] = ${JSON.stringify(reference, null, 2)};

/** The tool the model answers with: its input is \`{notes, plan}\`, the plan per plan.schema.json. */
export const SUBMIT_PLAN_TOOL = ${JSON.stringify(tool, null, 2)};
`);
console.log('Wrote src/plan/prompt.ts.');
